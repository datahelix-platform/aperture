/**
 * Introspection fixtures for adapter unit tests. Deliberately generic
 * (library-catalog nouns, not any real portal domain — ADR-0002); shaped like
 * a Hippo-style autogenerated read surface: list fields with
 * filter/limit/offset/search args, enum + relationship fields, a batch
 * mutation.
 */

/**
 * The captured `__schema` of a live `hippo serve` (v0.10.3, DataHelix
 * certification fixture schema) — aperture's own INTROSPECTION_QUERY against
 * it. This is the ground truth for the real read shapes (#15) — singular
 * detail fields, `{ items total }` page envelopes, bare-list search twins
 * with required `q`, the generic `[FilterInput!]` + FilterMode filter pair —
 * and the real write shapes: `create<T>(data:)`/`update<T>(id, data:)` plus
 * the `ingestBatch`/`validateBatch` batch unit-of-work.
 *
 * Kept unchanged as a record of that server, so it still advertises the enrichment as
 * `hippoSchema`. Aperture reads only `mosaicSchema` since platform ADR-0007 (Q3), so this
 * capture negotiates `schemaIntrospection: 'graphql'`. The two captures below are current
 * and exercise the `mosaicSchema` path.
 */
export const realIntrospection = realIntrospectionJson as unknown as IntrospectionSchema;

/**
 * The captured `__schema` of **mosaic v0.16.0** (pre-release: mosaic PR #284 at
 * `1423eb1`, the platform ADR-0007 identifier rename) over `mosaic-demo-small`'s
 * fifteen-collection demo schema **as of `7f98e3c`**, with only that repo's ADR-0007
 * rename (`6a679bb`) applied. First captured from v0.13.0, then refreshed to v0.14.0.
 *
 * Added beside `realIntrospection` rather than replacing it. The two answer
 * different questions and both are needed: `realIntrospection` is the capture
 * the read/write-shape and batch contracts are written against, and rewriting
 * it would re-baseline six test files for no gain here.
 *
 * What this one carries that the older capture cannot (ADR-0041):
 *
 * - **edge-only references** (Mosaic ADR-0005) — `Sample.donor` resolves to a
 *   `Donor` object and there is no `donorId` scalar beside it, so a referenced
 *   value is reachable *only* through a nested selection. The older capture
 *   predates that and still carries `Book.authorId` next to `Book.author`.
 * - **forward to-many references** — `Workflow.inputSamples`,
 *   `Publication.datasets`, `RunConfiguration.reagentLots`, each with a free
 *   `<rel>Count` companion. The older capture has no entity-level list-of-object
 *   field at all, so explode is untestable against it.
 * - **the typed filter surface** — `<Type>Filter` inputs with `and`/`or`/`not`
 *   and `SampleEdgeQuantifiers { some, none }` relationship predicates.
 *
 * The schema is pinned **before demo-small `3843214`** on purpose. That commit declares
 * four reverse edges (`Donor.samples`, `Donor.diagnoses`, `Sample.aliquots`,
 * `Workflow.datasets`), and this fixture is the half of the pair that has none.
 *
 * It therefore has **no reverse edges**: `Donor` has no `samples` field and
 * `DonorFilter` has no `samples` predicate. The reverse-edge gating is tested
 * against that.
 */
export const demoIntrospection = demoIntrospectionJson as unknown as IntrospectionSchema;

/**
 * The captured `__schema` of **mosaic v0.16.0** (pre-release: mosaic PR #284 at
 * `1423eb1`) over DataHelix's certification fixture schema (`portal_schema.yaml`,
 * fixture **1.2.0**). The fixture's `hippo_*` keys and its `hippo_core` import were
 * renamed to `mosaic_*` for the capture, which is the change datahelix#57 makes. First
 * captured from v0.14.0 over fixture 1.1.0.
 *
 * This is the fixture that carries **reverse edges as a real schema feature**
 * rather than a simulation, because fixture 1.1.0 was bumped to declare them:
 *
 * - `Author.books` + `booksCount` — an `inverse:`-declared virtual reverse edge
 *   (Mosaic ADR-0011). `Author` therefore has BOTH a declared reverse edge and
 *   an inferrable one (from `Book.author`), which is precisely the collision
 *   ADR-0041's declared-over-inferred precedence rule exists to resolve.
 * - `Book.coAuthors` + `coAuthorsCount` — a stored forward multivalued
 *   reference.
 * - `AuthorFilter.books` — the reverse relationship predicate on the typed
 *   filter surface.
 *
 * Together with `demoIntrospection` (fifteen collections, **no** reverse edges,
 * because `mosaic-demo-small`'s schema declares none) these two give the
 * before/after pair ADR-0041's capability gating needs: the same derivation
 * code must offer reverse display columns against one and honestly gate them
 * off against the other, with no branch on a version number.
 */
export const certIntrospection = certIntrospectionJson as unknown as IntrospectionSchema;

/**
 * The captured `__schema` of **mosaic v0.16.0** (released wheel) over Mosaic's own
 * closure fixture (`tests/support/closure_fixture.py`, #241), plus one to-one reference
 * into the family (`Measurement.sample: Sample`). Captured 2026-11-23 with Aperture's
 * INTROSPECTION_QUERY, including `possibleTypes`.
 *
 * It carries a FAMILY (Mosaic ADR-0014, Aperture ADR-0042): abstract `Sample` with kinds
 * `Brain` and `Blood`, emitted as a GraphQL INTERFACE with a read-only `samples` page,
 * `sample(id:)`, search, count, facets and field range, and no mutations. The interface
 * carries only the shared fields (`id`, `label`, `producedBy`); `SampleFilter` and
 * `SampleOrderField` also take the kind-only ones (`hemisphere`, `volumeMl`, `drawnFrom`).
 * References into it: `Measurement.sample` (to-one) and `Assay.inputs` (to-many). It also
 * has the concrete-parent case: `Process` with subclass `BankBrain`, and `Person` with
 * `Donor`.
 */
export const familyIntrospection = familyIntrospectionJson as unknown as IntrospectionSchema;

export const scalar = (name: string): TypeRef => ({ kind: 'SCALAR', name, ofType: null });
export const enumRef = (name: string): TypeRef => ({ kind: 'ENUM', name, ofType: null });
export const object = (name: string): TypeRef => ({ kind: 'OBJECT', name, ofType: null });
export const nonNull = (ofType: TypeRef): TypeRef => ({ kind: 'NON_NULL', name: null, ofType });
export const list = (ofType: TypeRef): TypeRef => ({ kind: 'LIST', name: null, ofType });

export const field = (
  name: string,
  type: TypeRef,
  args: IntrospectionInputValue[] = [],
): IntrospectionField => ({ name, args, type });

export const arg = (
  name: string,
  type: TypeRef,
  defaultValue: string | null = null,
): IntrospectionInputValue => ({ name, type, defaultValue });

export const objectType = (name: string, fields: IntrospectionField[]): IntrospectionType => ({
  kind: 'OBJECT',
  name,
  fields,
});

export const inputObjectType = (
  name: string,
  inputFields: IntrospectionInputValue[],
): IntrospectionType => ({ kind: 'INPUT_OBJECT', name, inputFields });

export const enumType = (name: string, values: string[]): IntrospectionType => ({
  kind: 'ENUM',
  name,
  enumValues: values.map((v) => ({ name: v })),
});

const listArgs = [
  arg('filter', { kind: 'INPUT_OBJECT', name: 'BookFilter', ofType: null }),
  arg('limit', scalar('Int')),
  arg('offset', scalar('Int')),
  arg('search', scalar('String')),
];

/** A capable, Hippo-like endpoint: pagination, filters, FTS, detail, history, batch write. */
export function capableSchema(
  options: {
    mosaicSchema?: boolean;
    authorDetail?: boolean;
    authorWrite?: boolean;
    /** Adds the Aperture control-plane document collection (Phase 4, N5.4). */
    documents?: boolean;
    /**
     * Adds the recipe-1.1.0 `owner`/`visibility` fields + filters to the
     * document collection (ADR-0032 ownership amendment). Without this the
     * collection is the 1.0.0 shape, which must still work — per-user scoping
     * simply does not light up.
     */
    documentOwnership?: boolean;
    /** Adds Book's availability-transition + supersede mutations (W4.4). */
    bookLifecycle?: boolean;
    /** Adds the conversational query mutation (ADR-0039). */
    conversational?: boolean;
  } = {},
): IntrospectionSchema {
  const queryFields = [
    field('books', nonNull(list(nonNull(object('Book')))), listArgs),
    field(
      'authors',
      nonNull(list(nonNull(object('Author')))),
      [arg('limit', scalar('Int')), arg('offset', scalar('Int'))],
    ),
    // Singular detail field (R3.7) — the preferred detail path for books.
    field('book', object('Book'), [arg('id', nonNull(scalar('ID')))]),
    // Entity change history (R3.7).
    field('entityHistory', nonNull(list(nonNull(object('HistoryEntry')))), [
      arg('entityId', nonNull(scalar('ID'))),
    ]),
  ];
  if (options.mosaicSchema) {
    queryFields.push(field('mosaicSchema', object('MosaicSchema')));
  }
  if (options.authorDetail) {
    queryFields.push(field('author', object('Author'), [arg('id', nonNull(scalar('ID')))]));
  }
  const authorFields = [field('id', nonNull(scalar('ID'))), field('name', scalar('String'))];
  if (options.authorDetail) {
    authorFields.push(field('books', list(nonNull(object('Book')))));
  }
  const mutationExtras: IntrospectionField[] = [];
  const typeExtras: IntrospectionType[] = [];
  const bookFields = [
    field('id', nonNull(scalar('ID'))),
    field('title', nonNull(scalar('String'))),
    field('published_on', scalar('Date')),
    field('page_count', scalar('Int')),
    field('in_print', scalar('Boolean')),
    field('format', enumRef('BookFormat')),
    field('author', object('Author')),
    field('reviews', list(nonNull(object('Review')))),
  ];
  if (options.bookLifecycle) {
    bookFields.push(field('isAvailable', nonNull(scalar('Boolean'))));
    mutationExtras.push(
      field('setBookAvailability', nonNull(object('AvailabilityResult')), [
        arg('id', nonNull(scalar('ID'))),
        arg('isAvailable', nonNull(scalar('Boolean'))),
        arg('reason', scalar('String')),
      ]),
      field('setBookAvailabilityBulk', nonNull(object('BulkAvailabilityResult')), [
        arg('ids', nonNull(list(nonNull(scalar('ID'))))),
        arg('isAvailable', nonNull(scalar('Boolean'))),
        arg('reason', scalar('String')),
      ]),
      field('supersedeBook', nonNull(object('SupersedeResult')), [
        arg('id', nonNull(scalar('ID'))),
        arg('replacementId', nonNull(scalar('ID'))),
        arg('reason', scalar('String')),
      ]),
    );
    typeExtras.push(
      objectType('AvailabilityResult', [
        field('entityId', nonNull(scalar('ID'))),
        field('isAvailable', nonNull(scalar('Boolean'))),
      ]),
      objectType('BulkAvailabilityResult', [
        field('total', nonNull(scalar('Int'))),
        field('succeeded', nonNull(scalar('Int'))),
        field('failed', nonNull(scalar('Int'))),
      ]),
      objectType('SupersedeResult', [
        field('entityId', nonNull(scalar('ID'))),
        field('supersededBy', nonNull(scalar('ID'))),
      ]),
    );
  }
  if (options.authorWrite) {
    mutationExtras.push(
      field('createAuthor', object('Author'), [
        arg('input', nonNull({ kind: 'INPUT_OBJECT', name: 'AuthorInput', ofType: null })),
      ]),
    );
    typeExtras.push(inputObjectType('AuthorInput', [arg('name', nonNull(scalar('String')))]));
  }
  const queryExtras: IntrospectionField[] = [];
  if (options.documents) {
    queryExtras.push(
      field('apertureDocuments', nonNull(list(nonNull(object('ApertureDocument')))), [
        arg('filter', { kind: 'INPUT_OBJECT', name: 'ApertureDocumentFilter', ofType: null }),
        arg('limit', scalar('Int')),
        arg('offset', scalar('Int')),
      ]),
    );
    mutationExtras.push(
      field('createApertureDocument', object('ApertureDocument'), [
        arg('input', nonNull({ kind: 'INPUT_OBJECT', name: 'ApertureDocumentInput', ofType: null })),
      ]),
      field('updateApertureDocument', object('ApertureDocument'), [
        arg('id', nonNull(scalar('ID'))),
        arg('input', nonNull({ kind: 'INPUT_OBJECT', name: 'ApertureDocumentUpdateInput', ofType: null })),
      ]),
    );
    const ownershipFields = options.documentOwnership
      ? [field('owner', scalar('String')), field('visibility', scalar('String'))]
      : [];
    const ownershipArgs = options.documentOwnership
      ? [arg('owner', scalar('String')), arg('visibility', scalar('String'))]
      : [];
    typeExtras.push(
      objectType('ApertureDocument', [
        field('id', nonNull(scalar('ID'))),
        field('kind', nonNull(scalar('String'))),
        field('name', nonNull(scalar('String'))),
        field('payload', nonNull(scalar('String'))),
        ...ownershipFields,
      ]),
      inputObjectType('ApertureDocumentFilter', [
        arg('kind', scalar('String')),
        arg('name', scalar('String')),
        ...ownershipArgs,
      ]),
      inputObjectType('ApertureDocumentInput', [
        arg('kind', nonNull(scalar('String'))),
        arg('name', nonNull(scalar('String'))),
        arg('payload', nonNull(scalar('String'))),
        ...ownershipArgs,
      ]),
      inputObjectType('ApertureDocumentUpdateInput', [
        arg('kind', scalar('String')),
        arg('name', scalar('String')),
        arg('payload', scalar('String')),
        ...ownershipArgs,
      ]),
    );
  }
  if (options.conversational) {
    // The shape mosaic-demo-small's add-aperture-chat-panel contract pins:
    // `{utterance, query_spec, turns, edit_turn_id}` in, `{turn, turns,
    // suspended_turn_ids}` out.
    mutationExtras.push(
      field('converseQuerySpec', nonNull(object('ConverseResult')), [
        arg('utterance', nonNull(scalar('String'))),
        arg('query_spec', scalar('JSON')),
        arg('turns', list(nonNull({ kind: 'INPUT_OBJECT', name: 'ConversationTurnInput', ofType: null }))),
        arg('edit_turn_id', scalar('ID')),
      ]),
    );
    typeExtras.push(
      objectType('ConverseResult', [
        field('turn', nonNull(object('ConversationTurn'))),
        field('turns', nonNull(list(nonNull(object('ConversationTurn'))))),
        field('suspended_turn_ids', nonNull(list(nonNull(scalar('ID'))))),
      ]),
      objectType('ConversationTurn', [
        field('id', nonNull(scalar('ID'))),
        field('utterance', nonNull(scalar('String'))),
        field('status', nonNull(scalar('String'))),
        field('message', nonNull(scalar('String'))),
        field('query_spec', scalar('JSON')),
      ]),
      inputObjectType('ConversationTurnInput', [
        arg('id', nonNull(scalar('ID'))),
        arg('utterance', nonNull(scalar('String'))),
        arg('status', nonNull(scalar('String'))),
        arg('message', nonNull(scalar('String'))),
        arg('query_spec', scalar('JSON')),
      ]),
    );
  }
  return {
    queryType: { name: 'Query' },
    mutationType: { name: 'Mutation' },
    types: [
      objectType('Query', [...queryFields, ...queryExtras]),
      objectType('Mutation', [
        // Batch unit-of-work (Hippo #84, real shape confirmed live — #15):
        // entity list + optional relationships + dry-run, plus a validate twin.
        field('ingestBatch', nonNull(object('BatchWriteGraphQLResult')), [
          arg(
            'entities',
            nonNull(list(nonNull({ kind: 'INPUT_OBJECT', name: 'BatchEntityInput', ofType: null }))),
          ),
          arg(
            'relationships',
            list(nonNull({ kind: 'INPUT_OBJECT', name: 'BatchRelationshipInput', ofType: null })),
          ),
          arg('dryRun', nonNull(scalar('Boolean'))),
        ]),
        field('validateBatch', nonNull(object('BatchValidationGraphQLResult')), [
          arg(
            'entities',
            nonNull(list(nonNull({ kind: 'INPUT_OBJECT', name: 'BatchEntityInput', ofType: null }))),
          ),
        ]),
        // Tier-0 write paths (W4.3): create takes an input; update adds an id.
        field('createBook', object('Book'), [
          arg('input', nonNull({ kind: 'INPUT_OBJECT', name: 'BookInput', ofType: null })),
        ]),
        field('updateBook', object('Book'), [
          arg('id', nonNull(scalar('ID'))),
          arg('input', nonNull({ kind: 'INPUT_OBJECT', name: 'BookUpdateInput', ofType: null })),
        ]),
        ...mutationExtras,
      ]),
      inputObjectType('BookInput', [
        arg('title', nonNull(scalar('String'))),
        arg('published_on', scalar('Date')),
        arg('page_count', scalar('Int')),
        arg('in_print', scalar('Boolean')),
        arg('format', enumRef('BookFormat')),
        arg('author', scalar('ID')),
        arg('tags', list(scalar('String'))), // multivalued — no Tier-0 widget, omitted
      ]),
      inputObjectType('BookUpdateInput', [
        arg('title', scalar('String')),
        arg('published_on', scalar('Date')),
        arg('page_count', scalar('Int')),
        arg('in_print', scalar('Boolean')),
        arg('format', enumRef('BookFormat')),
        arg('author', scalar('ID')),
      ]),
      inputObjectType('BookFilter', [
        arg('format', enumRef('BookFormat')),
        arg('in_print', scalar('Boolean')),
        arg('author', scalar('ID')),
        arg('title', scalar('String')), // plain text — not an equality facet
        arg('or', list(nonNull({ kind: 'INPUT_OBJECT', name: 'BookFilter', ofType: null }))),
      ]),
      objectType('HistoryEntry', [
        field('timestamp', nonNull(scalar('String'))),
        field('action', scalar('String')),
        field('actor', scalar('String')),
      ]),
      inputObjectType('BatchEntityInput', [
        arg('entityType', nonNull(scalar('String'))),
        arg('data', nonNull(scalar('JSON'))),
        arg('operation', nonNull(scalar('String'))), // defaults to "insert" server-side
      ]),
      inputObjectType('BatchRelationshipInput', [
        arg('sourceId', nonNull(scalar('ID'))),
        arg('targetId', nonNull(scalar('ID'))),
        arg('relationshipType', nonNull(scalar('String'))),
        arg('metadata', scalar('JSON')),
      ]),
      objectType('BatchWriteGraphQLResult', [
        field('committed', nonNull(scalar('Boolean'))),
        field('dryRun', nonNull(scalar('Boolean'))),
        field('validation', nonNull(object('BatchValidationGraphQLResult'))),
        field('entities', nonNull(list(nonNull(scalar('JSON'))))),
        field('relationships', nonNull(list(nonNull(scalar('JSON'))))),
      ]),
      objectType('BatchValidationGraphQLResult', [
        field('passed', nonNull(scalar('Boolean'))),
        field('results', nonNull(list(nonNull(object('BatchEntityValidation'))))),
      ]),
      objectType('BatchEntityValidation', [
        field('entityId', scalar('ID')),
        field('passed', nonNull(scalar('Boolean'))),
        field('failures', nonNull(list(nonNull(object('ValidationFailureType'))))),
      ]),
      objectType('ValidationFailureType', [
        field('tier', nonNull(scalar('String'))),
        field('rule', nonNull(scalar('String'))),
        field('message', nonNull(scalar('String'))),
        field('field', scalar('String')),
        field('details', scalar('JSON')),
      ]),
      objectType('Book', bookFields),
      objectType('Author', authorFields),
      objectType('Review', [field('id', nonNull(scalar('ID'))), field('rating', scalar('Int'))]),
      objectType('MosaicSchema', [field('version', scalar('String'))]),
      enumType('BookFormat', ['HARDCOVER', 'PAPERBACK', 'EBOOK']),
      ...typeExtras,
    ],
  };
}

/** A bare endpoint: list fields with no args, no mutations, no relationships. */
export function bareSchema(): IntrospectionSchema {
  return {
    queryType: { name: 'Query' },
    mutationType: null,
    types: [
      objectType('Query', [field('things', list(object('Thing')))]),
      objectType('Thing', [field('label', scalar('String'))]),
    ],
  };
}

/**
 * A minimal X1-shaped endpoint (Mosaic ADR-0007): envelope paging with
 * `orderBy`/`orderDir` on both the base list and its search twin, an
 * `id`/`label` entity, and an orderBy enum matching both columns.
 */
export function sortableSchema(): IntrospectionSchema {
  const pageArgs = [
    arg('limit', nonNull(scalar('Int'))),
    arg('offset', nonNull(scalar('Int'))),
    arg('orderBy', enumRef('ThingOrderField')),
    arg('orderDir', nonNull(enumRef('OrderDirection')), 'ASC'),
  ];
  return {
    queryType: { name: 'Query' },
    mutationType: null,
    types: [
      objectType('Query', [
        field('things', nonNull(object('ThingPage')), pageArgs),
        field('searchThings', nonNull(object('ThingPage')), [
          arg('q', nonNull(scalar('String'))),
          ...pageArgs,
        ]),
      ]),
      objectType('ThingPage', [
        field('items', nonNull(list(nonNull(object('Thing'))))),
        field('total', nonNull(scalar('Int'))),
      ]),
      objectType('Thing', [field('id', nonNull(scalar('ID'))), field('label', scalar('String'))]),
      enumType('ThingOrderField', ['ID', 'LABEL']),
    ],
  };
}

